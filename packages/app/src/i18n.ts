export type Translate = (key: Key, params?: Record<string, string | number>) => string

export interface I18n {
  lang: Lang
  t: Translate
  slotName(slot: Slot): string
  primaryName(key: PrimaryKey): string
  number(value: number): string
  date(iso: string): string
}

export function createI18n(lang: Lang): I18n {
  const dictionary = dictionaries[lang]
  const locale = lang === "fr" ? "fr-FR" : "en-GB"
  const numberFormat = new Intl.NumberFormat(locale)
  const dateFormat = new Intl.DateTimeFormat(locale, { dateStyle: "medium", timeStyle: "short" })
  return {
    lang,
    t: (key, params) => {
      let text = dictionary[key]
      if (params) {
        for (const [name, value] of Object.entries(params)) text = text.replaceAll(`{${name}}`, String(value))
      }
      return text
    },
    slotName: (slot) => slotNames[lang][slot],
    primaryName: (key) => primaryNames[lang][key],
    number: (value) => numberFormat.format(value),
    date: (iso) => {
      const date = new Date(iso)
      return Number.isNaN(date.getTime()) ? "" : dateFormat.format(date)
    },
  }
}

const cache = new Map<Lang, I18n>()

export function useI18n(): I18n {
  const lang = useStore((s) => s.lang)
  let i18n = cache.get(lang)
  if (!i18n) {
    i18n = createI18n(lang)
    cache.set(lang, i18n)
  }
  return i18n
}
